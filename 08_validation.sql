

USE DATABASE DV2_BANK_DEMO;

-- SCENARIO: RISK CATEGORY CHANGES INDEPENDENTLY

INSERT INTO LANDING.CRM_CUSTOMERS (
    BATCH_ID,
    CUSTOMER_ID,
    EMAIL,
    CITY,
    SOURCE_CHANGED_AT,
    CUSTOMER_SEGMENT,
    RISK_CATEGORY
)
VALUES (
    9, 'C001', 'asha@example.com', 'GURUGRAM',
    '2026-10-09 09:00:00', 'PREMIUM', 'HIGH'
);


-- Load only the separate Risk Satellite.
-- The customer contact Satellite does not need
-- a new version because its attributes are unchanged.

INSERT INTO RAW_VAULT.SAT_CUSTOMER_RISK (
    CUSTOMER_HK,
    LOAD_DTS,
    RECORD_SOURCE,
    HASH_DIFF,
    SOURCE_CHANGED_AT,
    RISK_CATEGORY
)
SELECT
    SHA2(UPPER(TRIM(S.CUSTOMER_ID)),256),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'CRM',
    SHA2(COALESCE(S.RISK_CATEGORY,'~NULL~'),256),
    S.SOURCE_CHANGED_AT,
    S.RISK_CATEGORY

FROM LANDING.CRM_CUSTOMERS S

WHERE S.BATCH_ID = 9
  AND NOT EXISTS (
      SELECT 1
      FROM RAW_VAULT.SAT_CUSTOMER_RISK T
      WHERE T.CUSTOMER_HK =
          SHA2(UPPER(TRIM(S.CUSTOMER_ID)),256)
        AND T.LOAD_DTS = (
            SELECT MAX(T2.LOAD_DTS)
            FROM RAW_VAULT.SAT_CUSTOMER_RISK T2
            WHERE T2.CUSTOMER_HK = T.CUSTOMER_HK
        )
        AND T.RISK_CATEGORY IS NOT DISTINCT FROM S.RISK_CATEGORY
  );


-- Compare historical version counts

SELECT
    'SAT_CUSTOMER_CRM' AS SATELLITE,
    COUNT(*) AS CUSTOMER_VERSIONS
FROM RAW_VAULT.SAT_CUSTOMER_CRM S
JOIN RAW_VAULT.HUB_CUSTOMER H
    ON S.CUSTOMER_HK = H.CUSTOMER_HK
WHERE H.CUSTOMER_ID = 'C001'

UNION ALL

SELECT
    'SAT_CUSTOMER_RISK',
    COUNT(*)
FROM RAW_VAULT.SAT_CUSTOMER_RISK S
JOIN RAW_VAULT.HUB_CUSTOMER H
    ON S.CUSTOMER_HK = H.CUSTOMER_HK
WHERE H.CUSTOMER_ID = 'C001';


-- Show C001's independent risk history

SELECT
    H.CUSTOMER_ID,
    R.RISK_CATEGORY,
    R.SOURCE_CHANGED_AT
FROM RAW_VAULT.SAT_CUSTOMER_RISK R
JOIN RAW_VAULT.HUB_CUSTOMER H
    ON R.CUSTOMER_HK = H.CUSTOMER_HK
WHERE H.CUSTOMER_ID = 'C001'
ORDER BY R.LOAD_DTS;


