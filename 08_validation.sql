FROM RAW_VAULT.HUB_LOAN;


-- 3. New Customer-Loan relationships

SELECT
    C.CUSTOMER_ID,
    L.LOAN_ID
FROM RAW_VAULT.LINK_CUSTOMER_LOAN CL
