
USE DATABASE DV2_BANK_DEMO;

-- =====================================================
-- APPROACH 2: CREATE A NEW SATELLITE
-- =====================================================

-- STEP 1: CRM introduces another attribute

ALTER TABLE LANDING.CRM_CUSTOMERS
ADD COLUMN IF NOT EXISTS RISK_CATEGORY VARCHAR;


-- STEP 2: Create a separate Satellite
-- Existing Hub and CRM Satellite remain unchanged.

CREATE TABLE IF NOT EXISTS
RAW_VAULT.SAT_CUSTOMER_RISK (
    CUSTOMER_HK VARCHAR(64),
    LOAD_DTS TIMESTAMP_NTZ,
    RECORD_SOURCE VARCHAR,
    HASH_DIFF VARCHAR(64),
    SOURCE_CHANGED_AT TIMESTAMP_NTZ,
    RISK_CATEGORY VARCHAR
);


-- STEP 3: Load a new CRM batch

INSERT INTO LANDING.CRM_CUSTOMERS (
    BATCH_ID,
    CUSTOMER_ID,
    EMAIL,
    CITY,
    SOURCE_CHANGED_AT,
    CUSTOMER_SEGMENT,
    RISK_CATEGORY
)
VALUES
(8, 'C001', 'asha@example.com', 'GURUGRAM',
 '2026-10-08 09:00:00', 'PREMIUM', 'LOW'),

(8, 'C002', 'rohan@example.com', 'MUMBAI',
 '2026-10-08 09:00:00', 'STANDARD', 'HIGH');


-- STEP 4: Load the new Satellite independently

INSERT INTO RAW_VAULT.SAT_CUSTOMER_RISK (
    CUSTOMER_HK,
    LOAD_DTS,
    RECORD_SOURCE,
    HASH_DIFF,
    SOURCE_CHANGED_AT,
    RISK_CATEGORY
)
WITH INCOMING AS (
    SELECT
        SHA2(UPPER(TRIM(CUSTOMER_ID)),256) AS CUSTOMER_HK,
        RISK_CATEGORY,
        SOURCE_CHANGED_AT,

        SHA2(
            COALESCE(RISK_CATEGORY, '~NULL~'),256
        ) AS HASH_DIFF

    FROM LANDING.CRM_CUSTOMERS
    WHERE BATCH_ID = 8

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_HK
        ORDER BY SOURCE_CHANGED_AT DESC
    ) = 1
),

LATEST AS (
    SELECT
        CUSTOMER_HK,
        RISK_CATEGORY
    FROM RAW_VAULT.SAT_CUSTOMER_RISK

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_HK
        ORDER BY LOAD_DTS DESC, SOURCE_CHANGED_AT DESC
    ) = 1
)

SELECT
    I.CUSTOMER_HK,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'CRM',
    I.HASH_DIFF,
    I.SOURCE_CHANGED_AT,
    I.RISK_CATEGORY

FROM INCOMING I
LEFT JOIN LATEST L
    ON I.CUSTOMER_HK = L.CUSTOMER_HK

WHERE L.CUSTOMER_HK IS NULL
   OR I.RISK_CATEGORY IS DISTINCT FROM L.RISK_CATEGORY;


-- STEP 5: Validate the new Satellite

SELECT
    H.CUSTOMER_ID,
    R.RISK_CATEGORY,
    R.LOAD_DTS
FROM RAW_VAULT.SAT_CUSTOMER_RISK R

JOIN RAW_VAULT.HUB_CUSTOMER H
    ON R.CUSTOMER_HK = H.CUSTOMER_HK

ORDER BY H.CUSTOMER_ID;
