
CREATE DATABASE IF NOT EXISTS DV2_BANK_DEMO;
CREATE SCHEMA IF NOT EXISTS DV2_BANK_DEMO.LANDING;
CREATE SCHEMA IF NOT EXISTS DV2_BANK_DEMO.STAGE;
CREATE SCHEMA IF NOT EXISTS DV2_BANK_DEMO.RAW_VAULT;
CREATE SCHEMA IF NOT EXISTS DV2_BANK_DEMO.MART;

CREATE TABLE IF NOT EXISTS DV2_BANK_DEMO.LANDING.CORE_CUSTOMERS (
  BATCH_ID NUMBER,
  CUSTOMER_ID VARCHAR,
  FULL_NAME VARCHAR,
  CUSTOMER_STATUS VARCHAR,
  SOURCE_CHANGED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS DV2_BANK_DEMO.LANDING.CORE_ACCOUNTS (
  BATCH_ID NUMBER,
  ACCOUNT_ID VARCHAR,
  CUSTOMER_ID VARCHAR,
  ACCOUNT_TYPE VARCHAR,
  ACCOUNT_STATUS VARCHAR,
  SOURCE_CHANGED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS DV2_BANK_DEMO.LANDING.CRM_CUSTOMERS (
  BATCH_ID NUMBER,
  CUSTOMER_ID VARCHAR,
  EMAIL VARCHAR,
  CITY VARCHAR,
  SOURCE_CHANGED_AT TIMESTAMP_NTZ
);

-- Landing retains its source rows. These views standardize keys and produce deterministic hashes.
--Hash Key (HK): Identifies a unique business entity or relationship.
--Hash Diff: Detects whether the descriptive attributes of that entity have changed.

CREATE OR REPLACE VIEW DV2_BANK_DEMO.STAGE.V_CORE_CUSTOMERS AS
SELECT 
BATCH_ID,
UPPER(TRIM(CUSTOMER_ID)) CUSTOMER_ID,
FULL_NAME,
CUSTOMER_STATUS,
SOURCE_CHANGED_AT,
SHA2(UPPER(TRIM(CUSTOMER_ID)),256) CUSTOMER_HK,
SHA2(CONCAT_WS('|',COALESCE(TRIM(FULL_NAME),'~NULL~'), COALESCE(TRIM(CUSTOMER_STATUS),'~NULL~')),256) HASH_DIFF
FROM DV2_BANK_DEMO.LANDING.CORE_CUSTOMERS
WHERE NULLIF(TRIM(CUSTOMER_ID),'') IS NOT NULL;

CREATE OR REPLACE VIEW DV2_BANK_DEMO.STAGE.V_CORE_ACCOUNTS AS
SELECT 
BATCH_ID, 
UPPER(TRIM(ACCOUNT_ID)) ACCOUNT_ID,
UPPER(TRIM(CUSTOMER_ID)) CUSTOMER_ID,
ACCOUNT_TYPE,
ACCOUNT_STATUS,
SOURCE_CHANGED_AT,
SHA2(UPPER(TRIM(ACCOUNT_ID)),256) ACCOUNT_HK,
SHA2(UPPER(TRIM(CUSTOMER_ID)),256) CUSTOMER_HK,
SHA2(CONCAT_WS('|',UPPER(TRIM(CUSTOMER_ID)),UPPER(TRIM(ACCOUNT_ID))),256) CUSTOMER_ACCOUNT_HK,
SHA2(CONCAT_WS('|',COALESCE(TRIM(ACCOUNT_TYPE),'~NULL~'),COALESCE(TRIM(ACCOUNT_STATUS),'~NULL~')),256) HASH_DIFF
FROM DV2_BANK_DEMO.LANDING.CORE_ACCOUNTS
WHERE NULLIF(TRIM(ACCOUNT_ID),'') IS NOT NULL
  AND NULLIF(TRIM(CUSTOMER_ID),'') IS NOT NULL;

CREATE OR REPLACE VIEW DV2_BANK_DEMO.STAGE.V_CRM_CUSTOMERS AS
SELECT 
BATCH_ID,
UPPER(TRIM(CUSTOMER_ID)) CUSTOMER_ID,
EMAIL,
CITY,
SOURCE_CHANGED_AT,
SHA2(UPPER(TRIM(CUSTOMER_ID)),256) CUSTOMER_HK,
SHA2(CONCAT_WS('|',COALESCE(TRIM(EMAIL),'~NULL~'),COALESCE(TRIM(CITY),'~NULL~')),256) HASH_DIFF
FROM DV2_BANK_DEMO.LANDING.CRM_CUSTOMERS
WHERE NULLIF(TRIM(CUSTOMER_ID),'') IS NOT NULL;

