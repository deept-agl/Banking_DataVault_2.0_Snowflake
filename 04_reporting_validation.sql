-- Customer Mart View
CREATE OR REPLACE VIEW DV2_BANK_DEMO.MART.V_CUSTOMER_CURRENT AS
WITH C AS (
  SELECT CUSTOMER_HK,
  FULL_NAME,
  CUSTOMER_STATUS
  FROM DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CORE
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_HK ORDER BY LOAD_DTS DESC)=1
), R AS (
  SELECT CUSTOMER_HK,
  EMAIL,
  CITY
  FROM DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CRM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_HK ORDER BY LOAD_DTS DESC)=1
)
SELECT H.CUSTOMER_ID,
C.FULL_NAME,
C.CUSTOMER_STATUS,
R.EMAIL,
R.CITY
FROM DV2_BANK_DEMO.RAW_VAULT.HUB_CUSTOMER H
LEFT JOIN C ON C.CUSTOMER_HK=H.CUSTOMER_HK
LEFT JOIN R ON R.CUSTOMER_HK=H.CUSTOMER_HK;

SELECT * FROM DV2_BANK_DEMO.MART.V_CUSTOMER_CURRENT;


-- Customer Account Mart View
CREATE OR REPLACE VIEW DV2_BANK_DEMO.MART.V_CUSTOMER_ACCOUNTS AS
WITH A AS (
  SELECT ACCOUNT_HK,
  ACCOUNT_TYPE,
  ACCOUNT_STATUS
  FROM DV2_BANK_DEMO.RAW_VAULT.SAT_ACCOUNT
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_HK ORDER BY LOAD_DTS DESC)=1
)
SELECT C.CUSTOMER_ID,
H.ACCOUNT_ID,
A.ACCOUNT_TYPE,
A.ACCOUNT_STATUS
FROM DV2_BANK_DEMO.RAW_VAULT.LINK_CUSTOMER_ACCOUNT L
JOIN DV2_BANK_DEMO.RAW_VAULT.HUB_CUSTOMER C ON C.CUSTOMER_HK=L.CUSTOMER_HK
JOIN DV2_BANK_DEMO.RAW_VAULT.HUB_ACCOUNT H ON H.ACCOUNT_HK=L.ACCOUNT_HK
LEFT JOIN A ON A.ACCOUNT_HK=H.ACCOUNT_HK;

SELECT * FROM DV2_BANK_DEMO.MART.V_CUSTOMER_ACCOUNTS;

