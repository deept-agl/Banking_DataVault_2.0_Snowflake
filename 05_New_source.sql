 'ACTIVE', 2500000, '2026-10-06 09:00:00'),
(6, 'L102', 'C004', 'PERSONAL_LOAN',
 'ACTIVE', 500000, '2026-10-06 09:00:00');


-- 3. Create new Data Vault structures

CREATE TABLE IF NOT EXISTS RAW_VAULT.HUB_LOAN (
    LOAN_HK VARCHAR(64),
    LOAN_ID VARCHAR,
    LOAD_DTS TIMESTAMP_NTZ,
    RECORD_SOURCE VARCHAR
);

CREATE TABLE IF NOT EXISTS RAW_VAULT.LINK_CUSTOMER_LOAN (
    CUSTOMER_LOAN_HK VARCHAR(64),
    CUSTOMER_HK VARCHAR(64),
    LOAN_HK VARCHAR(64),
    LOAD_DTS TIMESTAMP_NTZ,
    RECORD_SOURCE VARCHAR
);

CREATE TABLE IF NOT EXISTS RAW_VAULT.SAT_LOAN (
    LOAN_HK VARCHAR(64),
    LOAD_DTS TIMESTAMP_NTZ,
    RECORD_SOURCE VARCHAR,
    HASH_DIFF VARCHAR(64),
    SOURCE_CHANGED_AT TIMESTAMP_NTZ,
    LOAN_TYPE VARCHAR,
    LOAN_STATUS VARCHAR,
    LOAN_AMOUNT NUMBER(18,2)
);


-- 4. Create staging view for loan data

CREATE OR REPLACE VIEW STAGE.V_LOANS AS
SELECT
    BATCH_ID,
    UPPER(TRIM(LOAN_ID)) AS LOAN_ID,
    UPPER(TRIM(CUSTOMER_ID)) AS CUSTOMER_ID,
    LOAN_TYPE,
    LOAN_STATUS,
    LOAN_AMOUNT,
    SOURCE_CHANGED_AT,

    SHA2(UPPER(TRIM(LOAN_ID)), 256)
       AS LOAN_HK,

    SHA2(UPPER(TRIM(CUSTOMER_ID)), 256)
       AS CUSTOMER_HK,

    SHA2(
        CONCAT_WS('|',
            UPPER(TRIM(CUSTOMER_ID)),
            UPPER(TRIM(LOAN_ID))
        ), 256
    ) AS CUSTOMER_LOAN_HK,

    SHA2(
        CONCAT_WS('|',
            COALESCE(LOAN_TYPE, '~NULL~'),
            COALESCE(LOAN_STATUS, '~NULL~'),
            COALESCE(TO_VARCHAR(LOAN_AMOUNT), '~NULL~')
        ), 256
    ) AS HASH_DIFF

FROM LANDING.LOAN_CUSTOMERS;


-- 5. Reuse existing Customer Hub
-- Only new customer C004 should be inserted.

INSERT INTO RAW_VAULT.HUB_CUSTOMER
SELECT DISTINCT
    S.CUSTOMER_HK,
    S.CUSTOMER_ID,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'LOAN_SYSTEM'
FROM STAGE.V_LOANS S
WHERE S.BATCH_ID = 6
  AND NOT EXISTS (
      SELECT 1
      FROM RAW_VAULT.HUB_CUSTOMER H
      WHERE H.CUSTOMER_HK = S.CUSTOMER_HK
  );


-- 6. Load new Loan Hub

INSERT INTO RAW_VAULT.HUB_LOAN
SELECT DISTINCT
    S.LOAN_HK,
    S.LOAN_ID,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'LOAN_SYSTEM'
FROM STAGE.V_LOANS S
WHERE S.BATCH_ID = 6
  AND NOT EXISTS (
      SELECT 1
      FROM RAW_VAULT.HUB_LOAN H
      WHERE H.LOAN_HK = S.LOAN_HK
  );


-- 7. Load Customer-Loan relationship

INSERT INTO RAW_VAULT.LINK_CUSTOMER_LOAN
SELECT DISTINCT
    S.CUSTOMER_LOAN_HK,
    S.CUSTOMER_HK,
    S.LOAN_HK,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'LOAN_SYSTEM'
FROM STAGE.V_LOANS S
WHERE S.BATCH_ID = 6
  AND NOT EXISTS (
      SELECT 1
      FROM RAW_VAULT.LINK_CUSTOMER_LOAN L
      WHERE L.CUSTOMER_LOAN_HK = S.CUSTOMER_LOAN_HK
  );


-- 8. Load Loan Satellite

INSERT INTO RAW_VAULT.SAT_LOAN
SELECT
    S.LOAN_HK,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    'LOAN_SYSTEM',
    S.HASH_DIFF,
    S.SOURCE_CHANGED_AT,
    S.LOAN_TYPE,
    S.LOAN_STATUS,
    S.LOAN_AMOUNT
FROM STAGE.V_LOANS S
WHERE S.BATCH_ID = 6
  AND NOT EXISTS (
      SELECT 1
      FROM RAW_VAULT.SAT_LOAN T
      WHERE T.LOAN_HK = S.LOAN_HK
        AND T.HASH_DIFF = S.HASH_DIFF
  );


