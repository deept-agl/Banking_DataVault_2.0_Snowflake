
-- SCENARIO: A NEW LOAN MANAGEMENT SYSTEM IS INTRODUCED
-- Existing Customer and Account structures remain unchanged.

USE DATABASE DV2_BANK_DEMO;

-- 1. New source landing table

CREATE TABLE IF NOT EXISTS LANDING.LOAN_CUSTOMERS (
    BATCH_ID NUMBER,
    LOAN_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    LOAN_TYPE VARCHAR,
    LOAN_STATUS VARCHAR,
    LOAN_AMOUNT NUMBER(18,2),
    SOURCE_CHANGED_AT TIMESTAMP_NTZ
);

-- 2. New incoming data
-- C001 already exists; C004 is a new customer.

INSERT INTO LANDING.LOAN_CUSTOMERS
