
-- Assumes each source has no more than one row per business key per batch,
-- and batches are processed in ascending source sequence.
-- Replays are supported; out-of-order historical backfills need a more advanced loader.

CREATE OR REPLACE PROCEDURE DV2_BANK_DEMO.RAW_VAULT.LOAD_BATCH(P_BATCH NUMBER)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  --It stores the timestamp when the procedure starts.
  V_LOAD_DTS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;
BEGIN
  -- A transaction makes a batch all-or-nothing if an insert fails.
  BEGIN TRANSACTION;

  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.HUB_CUSTOMER
     (CUSTOMER_HK, CUSTOMER_ID, LOAD_DTS, RECORD_SOURCE)
  SELECT S.CUSTOMER_HK, S.CUSTOMER_ID, :V_LOAD_DTS, S.RECORD_SOURCE
  FROM (
     SELECT CUSTOMER_HK, CUSTOMER_ID, 'CORE' AS RECORD_SOURCE
     FROM DV2_BANK_DEMO.STAGE.V_CORE_CUSTOMERS WHERE BATCH_ID = :P_BATCH
     UNION ALL
     SELECT CUSTOMER_HK, CUSTOMER_ID, 'CRM' AS RECORD_SOURCE
     FROM DV2_BANK_DEMO.STAGE.V_CRM_CUSTOMERS WHERE BATCH_ID = :P_BATCH
  ) S
  WHERE NOT EXISTS (SELECT 1 FROM DV2_BANK_DEMO.RAW_VAULT.HUB_CUSTOMER H
                    WHERE H.CUSTOMER_HK = S.CUSTOMER_HK)
  QUALIFY ROW_NUMBER() OVER (PARTITION BY S.CUSTOMER_HK ORDER BY S.RECORD_SOURCE) = 1;

  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.HUB_ACCOUNT
     (ACCOUNT_HK, ACCOUNT_ID, LOAD_DTS, RECORD_SOURCE)
  SELECT S.ACCOUNT_HK, S.ACCOUNT_ID, :V_LOAD_DTS, 'CORE'
  FROM DV2_BANK_DEMO.STAGE.V_CORE_ACCOUNTS S
  WHERE S.BATCH_ID = :P_BATCH
    AND NOT EXISTS (SELECT 1 FROM DV2_BANK_DEMO.RAW_VAULT.HUB_ACCOUNT H
                    WHERE H.ACCOUNT_HK = S.ACCOUNT_HK);

  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.LINK_CUSTOMER_ACCOUNT
     (CUSTOMER_ACCOUNT_HK, CUSTOMER_HK, ACCOUNT_HK, LOAD_DTS, RECORD_SOURCE)
  SELECT S.CUSTOMER_ACCOUNT_HK, S.CUSTOMER_HK, S.ACCOUNT_HK, :V_LOAD_DTS, 'CORE'
  FROM DV2_BANK_DEMO.STAGE.V_CORE_ACCOUNTS S
  WHERE S.BATCH_ID = :P_BATCH
    AND NOT EXISTS (SELECT 1 FROM DV2_BANK_DEMO.RAW_VAULT.LINK_CUSTOMER_ACCOUNT L
                    WHERE L.CUSTOMER_ACCOUNT_HK = S.CUSTOMER_ACCOUNT_HK);

  -- Satellites are append only: compare source hashdiff with the most recent stored payload.
  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CORE
     (CUSTOMER_HK, LOAD_DTS, RECORD_SOURCE, HASH_DIFF, SOURCE_CHANGED_AT,
      FULL_NAME, CUSTOMER_STATUS)
  SELECT S.CUSTOMER_HK, :V_LOAD_DTS, 'CORE', S.HASH_DIFF,
         S.SOURCE_CHANGED_AT, S.FULL_NAME, S.CUSTOMER_STATUS
  FROM DV2_BANK_DEMO.STAGE.V_CORE_CUSTOMERS S
  LEFT JOIN (
     SELECT CUSTOMER_HK, HASH_DIFF FROM DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CORE
     QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_HK ORDER BY LOAD_DTS DESC) = 1
  ) T ON T.CUSTOMER_HK = S.CUSTOMER_HK
  WHERE S.BATCH_ID = :P_BATCH AND (T.CUSTOMER_HK IS NULL OR T.HASH_DIFF <> S.HASH_DIFF);

  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CRM
     (CUSTOMER_HK, LOAD_DTS, RECORD_SOURCE, HASH_DIFF, SOURCE_CHANGED_AT,
      EMAIL, CITY)
  SELECT S.CUSTOMER_HK, :V_LOAD_DTS, 'CRM', S.HASH_DIFF,
         S.SOURCE_CHANGED_AT, S.EMAIL, S.CITY
  FROM DV2_BANK_DEMO.STAGE.V_CRM_CUSTOMERS S
  LEFT JOIN (
     SELECT CUSTOMER_HK, HASH_DIFF FROM DV2_BANK_DEMO.RAW_VAULT.SAT_CUSTOMER_CRM
     QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_HK ORDER BY LOAD_DTS DESC) = 1
  ) T ON T.CUSTOMER_HK = S.CUSTOMER_HK
  WHERE S.BATCH_ID = :P_BATCH AND (T.CUSTOMER_HK IS NULL OR T.HASH_DIFF <> S.HASH_DIFF);

  INSERT INTO DV2_BANK_DEMO.RAW_VAULT.SAT_ACCOUNT
     (ACCOUNT_HK, LOAD_DTS, RECORD_SOURCE, HASH_DIFF, SOURCE_CHANGED_AT,
      ACCOUNT_TYPE, ACCOUNT_STATUS)
  SELECT S.ACCOUNT_HK, :V_LOAD_DTS, 'CORE', S.HASH_DIFF,
         S.SOURCE_CHANGED_AT, S.ACCOUNT_TYPE, S.ACCOUNT_STATUS
  FROM DV2_BANK_DEMO.STAGE.V_CORE_ACCOUNTS S
  LEFT JOIN (
     SELECT ACCOUNT_HK, HASH_DIFF FROM DV2_BANK_DEMO.RAW_VAULT.SAT_ACCOUNT
     QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_HK ORDER BY LOAD_DTS DESC) = 1
  ) T ON T.ACCOUNT_HK = S.ACCOUNT_HK
  WHERE S.BATCH_ID = :P_BATCH AND (T.ACCOUNT_HK IS NULL OR T.HASH_DIFF <> S.HASH_DIFF);

  COMMIT;
  RETURN 'Loaded batch ' || P_BATCH;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
